// Generates src/pages/content/scoped-preflight.css: Tailwind's preflight (global reset) with every
// selector limited to the extension's own containers, so it never touches Twitch's elements.
// Run `yarn css:scope-preflight` after changing tailwind.config.cjs or upgrading Tailwind.
const fs = require("node:fs");
const path = require("node:path");
const postcss = require("postcss");
const tailwind = require("tailwindcss");
const base = require("../tailwind.config.cjs");

// Our React roots, plus Headless UI's portal where the Manage Groups dialog renders
const SCOPE = ":where(#__root, #__manage-groups-root, #headlessui-portal-root)";
const OUT = path.resolve(__dirname, "../src/pages/content/scoped-preflight.css");

const buildBase = async (preflight) => {
  const config = { ...base, content: [{ raw: "", extension: "html" }], corePlugins: { ...(base.corePlugins || {}), preflight } };
  const result = await postcss([tailwind(config)]).process("@tailwind base;", { from: undefined });
  return result.root;
};

(async () => {
  const without = new Set();
  (await buildBase(false)).walkRules((rule) => without.add(rule.toString()));

  const preflight = await buildBase(true);
  const scoped = postcss.root();
  preflight.walkRules((rule) => {
    if (without.has(rule.toString())) return; // not part of preflight
    // The --tw-* custom property defaults are not part of the reset
    const props = [];
    rule.walkDecls((d) => props.push(d.prop));
    if (props.length > 0 && props.every((p) => p.startsWith("--tw-"))) return;
    const selectors = rule.selectors.filter((s) => !/^(html|:host|body)\b/.test(s.trim()));
    if (selectors.length === 0) return; // page-level rules (font, line-height) are not ours to set
    scoped.append(rule.clone({ selectors: selectors.map((s) => `${SCOPE} ${s.trim()}`) }));
  });

  const header = "/* GENERATED by scripts/scope-preflight.cjs - do not edit by hand.\n   Tailwind preflight, limited to the extension's own containers. */\n";
  fs.writeFileSync(OUT, header + scoped.toString() + "\n");
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${scoped.nodes.length} rules)`);
})();
